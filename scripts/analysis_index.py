#!/usr/bin/env python3
"""Generate analysis/INDEX.md from the front of every analysis/re-*.md, then list the other notes by title.

Usage: python3 scripts/analysis_index.py [--check] [--root DIR]
  --check     print the index to stdout, write nothing
  --root DIR  the checkout whose analysis/ to index (default: this script's own)
Any other argument is refused (exit 2) and -h / --help prints this: nothing but a plain run writes the tracked file.
`loopctl.py commit-docs` runs it and commits the index with any analysis/re-*.md; a landing that adds one does not
(the cleanse regenerates it, .claude/commands/cleanse.md pass 2).
Per file: title, first summary line, ELF function addresses mentioned (FUN_xxxxxxxx), status keywords,
'supersedes' mentions, line count. Grouped by area using filename keywords (first match wins).
"""
import glob, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AN = os.path.join(ROOT, "analysis")
AREAS = [  # (area, filename keywords)
    ("Soldier", ["soldier", "stance", "aim-assist", "knockback", "anim", "softskin", "zoom", "droideka-unit", "jetpack"]),
    ("AI / bots", ["-ai", "ai-", "squad", "kill-floor", "round-stalls", "droideka"]),
    ("Vehicles", ["vehicle", "hover", "walker", "turret", "command-walker"]),
    ("Weapons", ["weapon", "blaster", "bolt", "grenade", "ordnance", "powerup", "muzzle"]),
    ("HUD / UI", ["hud", "event-messages", "cheat"]),
    ("Audio", ["sound", "ambience", "announcer", "foley", "music"]),
    ("Rendering / fx", ["fog", "sky", "water", "terrain", "light", "glow", "fx", "foliage", "leafpatch", "spec", "alpha",
                        "texture", "material", "vertex", "vu1", "far-lowd", "lowr", "weather", "sun", "model"]),
    ("World / maps", ["kamino", "collision", "doors", "build-zones", "cp-", "pads"]),
    ("Modes / rules", ["conquest", "tickets", "time-limit", "spawn"]),
    ("Assets / formats", ["bank", "format", "lvl", "bake"]),
]
PRIVATE_BLOCK = re.compile(r"", re.S)
STATUS = ["PROVISIONAL", "UNAUDITED", "AUDITED", "SUPERSEDED", "STALE", "OPEN", "HYPOTHESIS"]


def area_of(name):
    n = name.lower()
    for area, keys in AREAS:
        if any(k in n for k in keys):
            return area
    return "Other"


def summarize(text):
    title, summ = None, None
    for line in text.splitlines()[:80]:
        s = line.strip()
        if not s:
            continue
        if s.startswith("#"):
            t = s.lstrip("# ").strip()
            if title is None and not re.match(r"(?i)opus re\b", t):
                title = t
            continue
        if title and summ is None and not s.startswith(("|", "```", "<!--", "---")):
            summ = s
            break
    return title or "(untitled)", (summ or "")[:220]


def main():
    global AN
    args = sys.argv[1:]
    if "-h" in args or "--help" in args:
        print(__doc__)
        return 0
    if "--root" in args:
        i = args.index("--root")
        if i + 1 >= len(args):
            print("analysis_index.py: --root needs a directory", file=sys.stderr)
            return 2
        AN = os.path.join(os.path.abspath(args[i + 1]), "analysis")
        del args[i:i + 2]
    unknown = [a for a in args if a != "--check"]
    if unknown:
        print(f"analysis_index.py: unknown argument(s) {' '.join(unknown)} (see --help)", file=sys.stderr)
        return 2
    rows = {}
    for p in sorted(glob.glob(os.path.join(AN, "re-*.md"))):
        name = os.path.basename(p)
        text = open(p, encoding="utf-8", errors="replace").read()
        title, summ = summarize(text)
        funcs = sorted(set(re.findall(r"FUN_([0-9a-fA-F]{6,8})", text)))
        stat = [k for k in STATUS if re.search(r"(?<![A-Za-z])" + k + r"(?![A-Za-z])", text)]
        sup = [m.strip()[:140] for m in re.findall(r"[^\n.]*[Ss]upersed(?:es|ed by)[^\n.]*", text)][:2]
        rows.setdefault(area_of(name), []).append((name, title, summ, funcs, stat, sup, text.count("\n") + 1))
    out = ["# analysis/ RE index", "",
           "GENERATED by `python3 scripts/analysis_index.py` - do not edit by hand. grep this file before starting any RE.", ""]
    order = [a for a, _ in AREAS] + ["Other"]
    for area in order:
        if area not in rows:
            continue
        out += [f"## {area}", ""]
        for name, title, summ, funcs, stat, sup, n in rows[area]:
            out.append(f"- **[{name}]({name})** ({n} lines) - {title}")
            if summ:
                out.append(f"  - {summ}")
            if funcs:
                shown = ", ".join("FUN_" + f for f in funcs[:8]) + (f" (+{len(funcs) - 8} more)" if len(funcs) > 8 else "")
                out.append(f"  - functions: {shown}")
            if stat:
                out.append(f"  - status: {', '.join(stat)}")
            for s in sup:
                out.append(f"  - supersedes: {s}")
        out.append("")
    others = [p for p in sorted(glob.glob(os.path.join(AN, "*.md")) + glob.glob(os.path.join(AN, "plan", "*.md")))
              if not os.path.basename(p).startswith("re-") and os.path.basename(p) != "INDEX.md"]
    if others:  # the notes that are not re-*: plans, audits, logs and state-of-play notes
        out += ["## Other notes", ""]
        for p in others:
            text = open(p, encoding="utf-8", errors="replace").read()
            public = PRIVATE_BLOCK.sub("", text)  # the export drops these blocks, and a note with nothing else
            if not public.strip():
                continue
            rel = os.path.relpath(p, AN).replace(os.sep, "/")
            out.append(f"- **[{rel}]({rel})** ({text.count(chr(10)) + 1} lines) - {summarize(public)[0]}")
        out.append("")
    text = "\n".join(out)
    if "--check" in args:
        sys.stdout.write(text)
    else:
        open(os.path.join(AN, "INDEX.md"), "w", encoding="utf-8").write(text)
        print(f"wrote analysis/INDEX.md: {sum(len(v) for v in rows.values())} files, {len(text.splitlines())} lines")
    return 0


sys.exit(main())
