#!/usr/bin/env python3
"""Technical issue cards. GitHub issues own the public backlog and assignments.

cards.py check | list [--write-backlog] | show ID | new ID --issue N --title TEXT
"""
import argparse
import fcntl
import os
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
LOOP = ROOT / "engine/artifacts/loop"
CARDS = Path(os.environ.get("OPENBF_CARDS_DIR", LOOP / "cards/private"))
FIELDS = ("id", "title", "issue", "status", "branch", "files", "declares")
STATUSES = {"todo", "in-progress", "review", "blocked", "done"}
PRIVATE_START = "<!-- " "private -->\n"
PRIVATE_END = "<!-- " "/private -->\n"


def read_card(path):
    path = Path(path)
    text = path.read_text()
    private = text.startswith(PRIVATE_START)
    if private:
        if not text.rstrip().endswith(PRIVATE_END.rstrip()):
            raise ValueError(f"{path}: unclosed private block")
        text = text[len(PRIVATE_START):].removesuffix(PRIVATE_END).rstrip() + "\n"
    match = re.fullmatch(r"---\n(.*?)\n---\n?(.*)", text, re.S)
    if not match:
        raise ValueError(f"{path}: missing card header")
    card = {"_path": str(path), "_body": match[2], "_private": private}
    for line in match[1].splitlines():
        key, sep, value = line.partition(":")
        key = key.strip()
        if not sep or not key or key in card:
            raise ValueError(f"{path}: invalid or duplicate header field {line!r}")
        card[key] = value.strip()
    return card


def write_card(card):
    unknown = set(card) - set(FIELDS) - {"_path", "_body", "_private"}
    if unknown:
        raise ValueError(f"unknown card fields: {', '.join(sorted(unknown))}")
    lines = [f"{key}: {card[key]}" for key in FIELDS if card.get(key)]
    text = "---\n" + "\n".join(lines) + "\n---\n" + card.get("_body", "")
    text = text.rstrip() + "\n"
    if card.get("_private", True):
        text = PRIVATE_START + text + PRIVATE_END
    Path(card["_path"]).write_text(text)


def cards():
    result = {}
    for path in sorted(CARDS.glob("*.md")):
        card = read_card(path)
        cid = card.get("id", "")
        if cid in result:
            raise ValueError(f"duplicate card id {cid}")
        result[cid] = card
    return result


def check(records=None):
    records = cards() if records is None else records
    errors = []
    issues = {}
    for cid, card in records.items():
        for field in ("id", "title", "issue", "status"):
            if not card.get(field):
                errors.append(f"{cid}: missing {field}")
        if not re.fullmatch(r"[A-Z][A-Z0-9-]*", cid) or Path(card["_path"]).stem != cid:
            errors.append(f"{cid}: invalid id or filename")
        if not re.fullmatch(r"[1-9][0-9]*", card.get("issue", "")):
            errors.append(f"{cid}: issue must be a positive issue number")
        elif card["issue"] in issues:
            errors.append(f"{cid}: issue #{card['issue']} already has card {issues[card['issue']]}")
        issues[card.get("issue", "")] = cid
        if card.get("status") not in STATUSES:
            errors.append(f"{cid}: unsupported status {card.get('status')!r}")
        for field in set(card) - set(FIELDS):
            if not field.startswith("_"):
                errors.append(f"{cid}: obsolete header field {field}")
        if not card.get("_private"):
            errors.append(f"{cid}: issue card needs an outer private block")
        for entry in card.get("files", "").split(","):
            entry = entry.strip()
            if entry and not entry.endswith(" (new)") and not (ROOT / entry).exists():
                errors.append(f"{cid}: path does not exist: {entry} (mark intended files '(new)')")
    return errors


def write_backlog(records=None):
    records = cards() if records is None else records
    lines = ["# Technical card index", "", "Generated by `python3 scripts/cards.py list --write-backlog`.",
             "GitHub issues are the public to-do list and ownership record. These links locate private technical detail.", ""]
    for card in sorted(records.values(), key=lambda c: int(c["issue"])):
        lines.append(f"- [#{card['issue']}](https://github.com/sprucey149/openbf/issues/{card['issue']}) "
                     f"[{card['id']}](cards/private/{card['id']}.md) — {card['title']}")
    lines.extend(["", "Historical technical evidence is in `cards/archive/`. An archived task does not claim acceptance or reserve work.",
                  "Reopen technical scope through its public issue before creating another active card.", ""])
    (LOOP / "BACKLOG.md").write_text(PRIVATE_START + "\n".join(lines) + PRIVATE_END)


def new_card(cid, issue, title):
    if not re.fullmatch(r"[A-Z][A-Z0-9-]*", cid):
        raise ValueError("id must contain uppercase letters, digits and hyphens")
    if issue < 1 or not title.strip() or "\n" in title or "\r" in title:
        raise ValueError("issue must be positive and title must be one nonempty line")
    CARDS.mkdir(parents=True, exist_ok=True)
    # Serialize creation by issue as well as filename across concurrent dispatchers.
    with (CARDS / ".new.lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        records = cards()
        if cid in records or any(c.get("issue") == str(issue) for c in records.values()):
            raise ValueError("a card already exists for this id or issue")
        # Ownership remains live on GitHub. Creation verifies it instead of copying it into a card.
        import json
        result = subprocess.run(["gh", "issue", "view", str(issue), "--repo", "sprucey149/openbf", "--json", "state,assignees"],
                                capture_output=True, text=True, check=True)
        live = json.loads(result.stdout)
        if live["state"] != "OPEN" or "sprucey149" not in {a["login"] for a in live["assignees"]}:
            raise ValueError("new work requires an open issue assigned to sprucey149")
        CARDS.mkdir(parents=True, exist_ok=True)
        path = CARDS / f"{cid}.md"
        card = dict(id=cid, title=title, issue=str(issue), status="todo", _private=True, _path=str(path),
                    _body="\n## Technical scope\n\n## Evidence and acceptance\n\n## Result\n")
        # Exclusive creation prevents two dispatchers from replacing the same brief.
        with path.open("x"):
            pass
        write_card(card)
        write_backlog()
        return path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("check")
    listing = commands.add_parser("list")
    listing.add_argument("--write-backlog", action="store_true")
    showing = commands.add_parser("show")
    showing.add_argument("id")
    creating = commands.add_parser("new")
    creating.add_argument("id")
    creating.add_argument("--issue", type=int, required=True)
    creating.add_argument("--title", required=True)
    args = parser.parse_args()
    try:
        if args.command == "new":
            print(new_card(args.id, args.issue, args.title))
            return 0
        records = cards()
        if args.command == "check":
            errors = check(records)
            print("\n".join(errors) if errors else f"{len(records)} cards, 0 problems, 0 path warnings")
            return bool(errors)
        if args.command == "show":
            if args.id in records:
                path = Path(records[args.id]["_path"])
            else:
                if not re.fullmatch(r"[A-Z][A-Z0-9-]*", args.id):
                    raise ValueError("invalid card id")
                path = LOOP / "cards/archive" / f"{args.id}.md"
            print(path.read_text(), end="")
        else:
            for card in sorted(records.values(), key=lambda c: int(c["issue"])):
                print(f"{card['id']}  #{card['issue']}  {card['status']}  {card['title']}")
            if args.write_backlog:
                write_backlog(records)
    except (ValueError, OSError, subprocess.CalledProcessError) as exc:
        print(f"cards: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
