//! The one bake entry point for an Xbox disc: `bake xbox`, and the rule it keeps.
//!
//! PS2 is the gameplay reference: every build plays the same whatever discs went
//! in, and other versions change only the size and look of assets. The two discs do differ in what the sim reads, measured here per map
//! by [`print_map`] (`analysis/xbox-input.md` has the table). So there are two
//! ways to bake from an Xbox disc, and they are not equally good:
//!
//! - **With the PS2 disc's tree** (`--ps2`): the map bakes from the PS2 LVL and
//!   the Xbox LVL only donates larger art of the same painting to tier 2
//!   ([`crate::tier`]). Nothing the sim reads can come from the Xbox.
//! - **Alone**: the map bakes from the Xbox LVL.
//!
//! Either way its gameplay sections are hashed and compared with [`PRINTS`], the
//! PS2's hashes shipped in the repo (hashes of names and numbers, no meshes, art
//! or audio), with its foliage as plain counts. A map that differs in any section, or any map when a side's class
//! numbers differ, is **refused** unless `--allow-gameplay-drift`, because a
//! numbers table cannot rebuild a differing collision mesh or heightfield. So a
//! tree handed to `--ps2` has to earn the name: a PC tree or a different revision
//! is refused by what it holds. The report says what drifted either way.

