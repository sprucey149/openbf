/// Where an Xbox disc keeps its LVLs, and where [`extract`] writes them.
pub const DATA_ROOT: &str = "Data/_LVL_XBOX";

const MOVIES_PREFIX: &str = "data/_lvl_xbox/movies/";
const KEPT_MOVIE: &str = "data/_lvl_xbox/movies/shell.mvs";

/// Every file under an Xbox disc's [`DATA_ROOT`] but its FMV, save the shell
/// background movie, to `<out>/Data/_LVL_XBOX/...`. A file already there at the
/// same size is left alone, so a second run writes nothing. Returns
/// `(written, kept, bytes written)`.
pub fn extract(iso: &Path, out: &Path) -> Result<(usize, usize, u64)> {
    let f = std::fs::File::open(iso).with_context(|| iso.display().to_string())?;
    let mut disc = mungefs::xdvdfs::Xdvdfs::open(std::io::BufReader::new(f))
        .map_err(|e| anyhow!("{}: not an Xbox XDVDFS image ({e})", iso.display()))?;
    let root = format!("{}/", DATA_ROOT.to_ascii_lowercase());
    let want: Vec<_> = disc
        .files
        .iter()
        .filter(|f| {
            let p = f.path.to_ascii_lowercase();
            p.starts_with(&root) && (!p.starts_with(MOVIES_PREFIX) || p == KEPT_MOVIE)
        })
        .cloned()
        .collect();
    if want.is_empty() {
        bail!(
            "{}: no {DATA_ROOT} directory (not an Xbox Battlefront disc?)",
            iso.display()
        );
    }
    let (mut wrote, mut kept, mut bytes) = (0, 0, 0u64);
    for entry in want {
        if !safe_disc_path(&entry.path) {
            bail!("{}: refusing the path {:?}", iso.display(), entry.path);
        }
        let dst = out.join(&entry.path);
        if std::fs::metadata(&dst).is_ok_and(|m| m.len() == u64::from(entry.size)) {
            kept += 1;
            continue;
        }
        let data = disc
            .read_file(&entry)
            .map_err(|e| anyhow!("{}: {e}", entry.path))?;
        std::fs::create_dir_all(dst.parent().unwrap())?;
        std::fs::write(&dst, &data).with_context(|| dst.display().to_string())?;
        wrote += 1;
        bytes += u64::from(entry.size);
    }
    Ok((wrote, kept, bytes))
}

/// Which game a data root holds, by content: the file only that game ships, in
/// any case.
pub fn identify(data_root: &Path) -> Option<&'static str> {
    let is_file = |rel: &str| crate::join_ci(data_root, rel).is_file();
    if !is_file("core.lvl") {
        None
    } else if is_file("ingame.lvl") {
        Some("bf2")
    } else if is_file("common/eng/common.lvl") {
        Some("bf1")
    } else {
        None
    }
}

fn fnv64(hash: &mut u64, bytes: &[u8]) {
    for &b in bytes {
        *hash ^= u64::from(b);
        *hash = hash.wrapping_mul(0x0100_0000_01b3);
    }
}

const FNV64_BASIS: u64 = 0xcbf2_9ce4_8422_2325;

fn hash_ron<T: Serialize>(value: &T) -> Result<u64> {
    let mut h = FNV64_BASIS;
    fnv64(&mut h, ron::ser::to_string(value)?.as_bytes());
    Ok(h)
}

/// One map's gameplay sections as hashes: the numbers and shapes the sim installs
/// from a map bake, and nothing it only draws. A difference proves the bytes
/// differ, not that a player could tell. Not covered, so a match is not the whole
/// proof: the door and turret rigs in `Manifest::classes`, and the model GLBs that
/// `game::stations` measures, both of which also hold what only draws.
pub fn print_map(lvl: &str, out: &Path, m: &Manifest) -> Result<BTreeMap<String, u64>> {
    let mut sections = BTreeMap::new();
    // Print what the bake read: on a corrected source that is not the raw file.
    let buf = crate::gameplay::read(lvl).with_context(|| lvl.to_string())?;
    let inner = mungefs::open(&buf).map_err(|e| anyhow!("{lvl}: {e}"))?;
    let mut heights = FNV64_BASIS;
    for c in mungefs::chunks(inner).flatten() {
        if &c.tag == b"tern" && !mungefs::terrain::Terrain::is_stub(&c) {
            let mut t = mungefs::terrain::Terrain::parse(&c).map_err(|e| anyhow!("{lvl}: {e}"))?;
            crate::gameplay::apply_terrain(lvl, &mut t)?;
            fnv64(&mut heights, &t.info.grid_unit.to_le_bytes());
            fnv64(&mut heights, &t.info.height_scale.to_le_bytes());
            fnv64(&mut heights, &t.info.grid_size.to_le_bytes());
            for h in &t.raw {
                fnv64(&mut heights, &h.to_le_bytes());
            }
        }
    }
    sections.insert("heights".to_owned(), heights);
    sections.insert("cutters".to_owned(), hash_ron(&m.terrain_cutters)?);
    sections.insert("game".to_owned(), hash_ron(&m.source_game)?);
    // The level and the wet cells: `Scene::install_water` gives the sim both.
    sections.insert(
        "water".to_owned(),
        hash_ron(&m.water.as_ref().map(|w| (w.height, &w.wet)))?,
    );
    sections.insert("instances".to_owned(), hash_ron(&m.instances)?);
    sections.insert("regions".to_owned(), hash_ron(&m.regions)?);
    sections.insert("paths".to_owned(), hash_ron(&m.paths)?);
    sections.insert("layers".to_owned(), hash_ron(&m.layers)?);

    let mut collision = hash_ron(&m.collision)?;
    for e in &m.collision {
        if let Some(glb) = e.glb.as_deref() {
            let bytes = std::fs::read(out.join(glb))
                .with_context(|| format!("{}: {glb}", out.display()))?;
            fnv64(&mut collision, &bytes);
        }
    }
    sections.insert("collision".to_owned(), collision);

    let mut nav = hash_ron(&m.nav)?;
    let mut nav_files: Vec<PathBuf> = std::fs::read_dir(out.join("nav"))
        .map(|d| d.flatten().map(|e| e.path()).collect())
        .unwrap_or_default();
    nav_files.sort();
    for p in nav_files {
        fnv64(&mut nav, &std::fs::read(&p)?);
    }
    sections.insert("nav".to_owned(), nav);

    sections.extend(foliage_sections(m));

    let mut classes = FNV64_BASIS;
    let map_classes = out.join(crate::map::MAP_CLASSES_FILE);
    fnv64(&mut classes, &std::fs::read(&map_classes)?);
    sections.insert("classes".to_owned(), classes);
    Ok(sections)
}

/// A map's foliage as plain counts, not a hash: it only draws, but a build that lost
/// it is plainly not the same map (no ELF once cost every disc build its 94,486
/// instances, and a control bake from the same extraction lost them too). Counts, so
/// a check can name what went missing, and so libm's last bit on another OS cannot
/// fail a good build.
fn foliage_sections(m: &Manifest) -> [(String, u64); 3] {
    let (count, props, grass) = m
        .foliage
        .as_ref()
        .map_or((0, 0, 0), |f| (f.count, f.path_props.len(), f.grass.len()));
    [
        (SECTION_INSTANCES.to_owned(), u64::from(count)),
        (SECTION_PATH_PROPS.to_owned(), props as u64),
        (SECTION_GRASS.to_owned(), grass as u64),
    ]
}

const SECTION_INSTANCES: &str = "foliage_instances";
const SECTION_PATH_PROPS: &str = "foliage_path_props";
const SECTION_GRASS: &str = "foliage_grass";

/// What [`check_foliage`] found across a baked tree.
#[derive(Debug, Default, PartialEq)]
pub struct FoliageReport {
    pub maps: usize,
    pub instances: u64,
    pub grass: u64,
    /// Maps missing a kind of foliage the PS2's print holds.
    pub lost: Vec<String>,
    /// The same, on a game whose gameplay is not the PS2's, which owes no such counts.
    pub excused: Vec<String>,
    /// Maps holding every kind, in other amounts.
    pub differ: Vec<String>,
}

impl FoliageReport {
    pub fn summary(&self) -> String {
        format!(
            "foliage: {} instances and {} grass classes on {} maps, {} lost, {} differing",
            self.instances,
            self.grass,
            self.maps,
            self.lost.len() + self.excused.len(),
            self.differ.len()
        )
    }
}

/// Compare one map's counts with the PS2's print, adding to `report`.
fn check_map_foliage(
    key: &str,
    got: &[(String, u64); 3],
    want: &BTreeMap<String, u64>,
    excused: bool,
    report: &mut FoliageReport,
) {
    let describe = |rows: &[&(String, u64)]| {
        rows.iter()
            .map(|(name, have)| format!("{name} {have} of {}", want.get(name).unwrap_or(&0)))
            .collect::<Vec<_>>()
            .join(", ")
    };
    let wanted = |name: &String| want.get(name).copied().unwrap_or(0);
    let lost: Vec<_> = got
        .iter()
        .filter(|(name, have)| *have == 0 && wanted(name) > 0)
        .collect();
    let differ: Vec<_> = got
        .iter()
        .filter(|(name, have)| *have != wanted(name))
        .collect();
    if !lost.is_empty() {
        let line = format!("{key}: {}", describe(&lost));
        if excused {
            report.excused.push(line);
        } else {
            report.lost.push(line);
        }
    } else if !differ.is_empty() {
        report.differ.push(format!("{key}: {}", describe(&differ)));
    }
}

/// Every baked map's foliage against the PS2's print. A map not in this tree is not
/// a fault: a partial bake says so itself. `bake xbox` holds its maps to the same
/// counts through [`print_map`]; this reaches a tree any bake wrote, including a
/// cached one, and needs no second bake to compare with: two bakes of one bad
/// extraction agree with each other. `excuse` names the games (`bf1`, `bf2`) that do
/// not bake from a PS2 tree: what they lost is reported apart, and fails nothing.
pub fn check_foliage(tree: &Path, excuse: &[String]) -> Result<FoliageReport> {
    let prints = shipped_prints()?;
    let mut report = FoliageReport::default();
    let excused = |game: &str| excuse.iter().any(|g| g == game);
    let maps = BF1_MAPS
        .iter()
        .map(|m| (m, "bf1"))
        .chain(BF2_MAPS.iter().map(|m| (m, "bf2")));
    for ((key, _), game) in maps {
        let path = tree.join(key).join("manifest.ron");
        if !path.is_file() {
            continue;
        }
        let text = std::fs::read_to_string(&path).with_context(|| path.display().to_string())?;
        let m: Manifest = ron::from_str(&text).with_context(|| path.display().to_string())?;
        let got = foliage_sections(&m);
        report.maps += 1;
        report.instances += got[0].1;
        report.grass += got[2].1;
        let want = prints
            .get(*key)
            .ok_or_else(|| anyhow!("{key}: no PS2 print"))?;
        check_map_foliage(key, &got, want, excused(game), &mut report);
    }
    Ok(report)
}

/// The PS2's prints, as shipped.
pub fn shipped_prints() -> Result<BTreeMap<String, BTreeMap<String, u64>>> {
    serde_json::from_str(PRINTS).context("the shipped PS2 gameplay prints")
}

/// The sections of `got` that differ from the reference `want`, sorted.
pub fn drift(got: &BTreeMap<String, u64>, want: &BTreeMap<String, u64>) -> Vec<String> {
    let mut names: Vec<&String> = got.keys().chain(want.keys()).collect();
    names.sort();
    names.dedup();
    names
        .into_iter()
        .filter(|n| got.get(*n) != want.get(*n))
        .cloned()
        .collect()
}

/// What `bake xbox` is asked for.
pub struct Options {
    /// An Xbox disc image, or a data root already extracted.
    pub source: PathBuf,
    pub out: PathBuf,
    /// The same game's PS2 data root. With it, gameplay is the PS2's.
    pub ps2: Option<PathBuf>,
    /// Only these map keys (`bf2_geo1`, `tat1`, ...).
    pub only: Option<Vec<String>>,
    /// Bake and keep a map whose gameplay differs from the PS2's, for testing.
    pub allow_gameplay_drift: bool,
}

/// One map's outcome.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct MapReport {
    pub key: String,
    /// Where the sim's data came from: `ps2` or `xbox`.
    pub gameplay: String,
    /// False when the map was refused and its output removed.
    pub baked: bool,
    /// The gameplay sections that differ from the PS2's.
    pub drift: Vec<String>,
    /// Textures in this bake, and how many have a larger copy beside them.
    pub textures: usize,
    pub tier2: usize,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct Report {
    pub game: String,
    pub data_root: String,
    pub maps: Vec<MapReport>,
    /// The side and common class files of the tree the maps bake from whose
    /// numbers differ from the PS2's. The rebake reads these, and every map plays
    /// on them, so one entry here is drift on every map.
    pub class_drift: Vec<String>,
}

/// The name of the report under the out dir.
pub const REPORT_FILE: &str = "xbox_report.ron";

fn data_root_of(source: &Path, out: &Path) -> Result<PathBuf> {
    if source.is_dir() {
        let nested = crate::join_ci(source, DATA_ROOT);
        return Ok(if nested.is_dir() {
            nested
        } else {
            source.to_owned()
        });
    }
    // One folder per image: `<out>` takes both games' maps, and a game is told
    // from the files in its tree, so BF2's `ingame.lvl` must not sit in BF1's. A
    // hash and not the image's name, because a donor list is comma-joined and
    // Redump's names hold commas.
    let mut id = FNV64_BASIS;
    fnv64(
        &mut id,
        source.file_name().unwrap_or_default().as_encoded_bytes(),
    );
    fnv64(
        &mut id,
        &std::fs::metadata(source)
            .with_context(|| source.display().to_string())?
            .len()
            .to_le_bytes(),
    );
    let dest = out.join(".xbox_source").join(format!("{id:016x}"));
    let (wrote, kept, bytes) = extract(source, &dest)?;
    println!(
        "xbox: {wrote} files written ({} MB), {kept} already there -> {}",
        bytes >> 20,
        dest.display()
    );
    Ok(crate::join_ci(&dest, DATA_ROOT))
}

/// `bake xbox`. See the module doc. An error names what was refused; the report
/// is written first, so the caller can read why.
pub fn bake_xbox(o: &Options) -> Result<Report> {
    std::fs::create_dir_all(&o.out)?;
    let root = data_root_of(&o.source, &o.out)?;
    let game = identify(&root)
        .ok_or_else(|| anyhow!("{}: not a Battlefront data root", root.display()))?;
    if let Some(ps2) = &o.ps2 {
        if identify(ps2) != Some(game) {
            bail!("{}: not the PS2 data root of {game}", ps2.display());
        }
    }
    let maps: &[(&str, &str)] = if game == "bf1" { &BF1_MAPS } else { &BF2_MAPS };
    if let Some(only) = &o.only {
        if let Some(bad) = only.iter().find(|k| !maps.iter().any(|(m, _)| m == k)) {
            bail!("no map {bad:?} on {game}");
        }
    }
    // Which disc a tree came from decides what the report's `gameplay` means, so
    // it is read from the LVLs and not taken from the argument's position.
    let selected = || {
        maps.iter()
            .filter(|(key, _)| o.only.as_ref().is_none_or(|k| k.iter().any(|m| m == key)))
    };
    for (_, rel) in selected() {
        let lvl = crate::join_ci(&root, rel);
        if !lvl.is_file() {
            bail!("{}: no {rel}", root.display());
        }
        if !lvl_is_xbox(&lvl.to_string_lossy())? {
            bail!("{}: not an Xbox LVL", lvl.display());
        }
        if let Some(ps2) = &o.ps2 {
            let lvl = crate::join_ci(ps2, rel);
            if lvl.is_file() && lvl_is_xbox(&lvl.to_string_lossy())? {
                bail!("{}: --ps2 was given an Xbox LVL", lvl.display());
            }
        }
    }
    let prints = shipped_prints()?;

    let mut report = Report {
        game: game.to_owned(),
        data_root: root.display().to_string(),
        maps: Vec::new(),
        class_drift: Vec::new(),
    };
    let class_root = o.ps2.as_ref().unwrap_or(&root);
    let files: &[(&str, &str)] = if game == "bf1" {
        &BF1_CLASSES
    } else {
        &BF2_CLASSES
    };
    for (key, rel) in files {
        let lvl = crate::join_ci(class_root, rel)
            .to_string_lossy()
            .into_owned();
        let got = print_classes(&lvl, &o.out.join(".xbox_work"), key)?;
        if prints.get(*key) != Some(&got) {
            report.class_drift.push((*key).to_owned());
        }
    }
    std::fs::remove_dir_all(o.out.join(".xbox_work")).ok();
    for (key, rel) in selected() {
        let xbox_lvl = crate::join_ci(&root, rel);
        let out = o.out.join(key);
        let out_str = out.to_string_lossy().into_owned();
        // A stale tree could otherwise be hashed into this map's print.
        for sub in ["models", "textures", "collision", "nav"] {
            let _ = std::fs::remove_dir_all(out.join(sub));
        }
        let xbox_str = xbox_lvl.to_string_lossy().into_owned();
        let (lvl, donor, source) = match &o.ps2 {
            Some(ps2) => (
                crate::join_ci(ps2, rel).to_string_lossy().into_owned(),
                Some(xbox_str.as_str()),
                "ps2",
            ),
            None => (xbox_str.clone(), None, "xbox"),
        };
        let m = crate::map::bake_map(&lvl, &out_str, donor)
            .with_context(|| format!("{key}: baking {lvl}"))?;
        let load = crate::join_ci(&root, &format!("LOAD/{}", rel.rsplit('/').next().unwrap()));
        if load.is_file() {
            crate::loadscreen::bake_loadscreen(&load.to_string_lossy(), &out_str)
                .with_context(|| format!("{key}: {}", load.display()))?;
        }
        let got = print_map(&lvl, &out, &m)?;
        let drifted = match prints.get(*key) {
            Some(want) => drift(&got, want),
            None => vec!["no PS2 print for this map".to_owned()],
        };
        let refused =
            (!drifted.is_empty() || !report.class_drift.is_empty()) && !o.allow_gameplay_drift;
        if refused {
            std::fs::remove_dir_all(&out).ok();
        }
        report.maps.push(MapReport {
            key: (*key).to_owned(),
            gameplay: source.to_owned(),
            baked: !refused,
            drift: drifted,
            textures: m.textures.len(),
            tier2: m.texture_tier2.len(),
        });
    }
    crate::write_ron(&o.out.join(REPORT_FILE), &report)?;
    let refused: Vec<&str> = report
        .maps
        .iter()
        .filter(|m| !m.baked)
        .map(|m| m.key.as_str())
        .collect();
    if !refused.is_empty() {
        bail!(
            "refused {} map(s) whose gameplay differs from the PS2's: {}. Bake from the PS2 disc, or see {}",
            refused.len(),
            refused.join(" "),
            o.out.join(REPORT_FILE).display()
        );
    }
    Ok(report)
}

/// True when any texture in the LVL has the Xbox layout.
pub(crate) fn lvl_is_xbox(lvl: &str) -> Result<bool> {
    let buf = std::fs::read(lvl).with_context(|| lvl.to_string())?;
    let inner = mungefs::open(&buf).map_err(|e| anyhow!("{lvl}: {e}"))?;
    Ok(mungefs::content_chunks(inner)
        .map_err(|e| anyhow!("{lvl}: {e}"))?
        .iter()
        .any(|c| &c.tag == b"tex_" && mungefs::texture_xbox::is_xbox(c)))
}

/// A path off a disc can only name a place under the extraction folder: no empty,
/// `.` or `..` part, and nothing another OS would read as a separator or a drive.
fn safe_disc_path(path: &str) -> bool {
    !path.contains(['\\', ':', '\0'])
        && path
            .split('/')
            .all(|c| !c.is_empty() && c != "." && c != "..")
}

/// `bake xbox-prints`: bake each PS2 map to `work` and write the prints [`PRINTS`]
/// ships. Refuses an Xbox tree, so a table can only ever hold the reference.
pub fn write_prints(ps2_roots: &[PathBuf], work: &Path, file: &Path) -> Result<()> {
    let mut all = BTreeMap::new();
    for root in ps2_roots {
        let game = identify(root).ok_or_else(|| anyhow!("{}: no game", root.display()))?;
        let maps: &[(&str, &str)] = if game == "bf1" { &BF1_MAPS } else { &BF2_MAPS };
        for (key, rel) in maps {
            let lvl = crate::join_ci(root, rel).to_string_lossy().into_owned();
            if lvl_is_xbox(&lvl)? {
                bail!("{lvl}: an Xbox LVL cannot define the PS2 reference");
            }
            let out = work.join(key);
            std::fs::remove_dir_all(&out).ok();
            let m = crate::map::bake_map(&lvl, &out.to_string_lossy(), None)?;
            all.insert((*key).to_owned(), print_map(&lvl, &out, &m)?);
        }
        let files: &[(&str, &str)] = if game == "bf1" {
            &BF1_CLASSES
        } else {
            &BF2_CLASSES
        };
        for (key, rel) in files {
            let lvl = crate::join_ci(root, rel).to_string_lossy().into_owned();
            all.insert((*key).to_owned(), print_classes(&lvl, work, key)?);
        }
    }
    let mut json = serde_json::to_string_pretty(&all)?;
    json.push('\n');
    std::fs::write(file, json).with_context(|| file.display().to_string())
}

