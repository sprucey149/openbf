/// One class file's print: `{"classes": hash}`, like a map's section.
fn print_classes(lvl: &str, work: &Path, key: &str) -> Result<BTreeMap<String, u64>> {
    std::fs::create_dir_all(work)?;
    let file = work.join(format!("{key}.ron"));
    crate::classes::bake_classes(lvl, &file.to_string_lossy())
        .with_context(|| format!("{key}: {lvl}"))?;
    let mut h = FNV64_BASIS;
    fnv64(&mut h, &std::fs::read(&file)?);
    std::fs::remove_file(&file).ok();
    Ok(BTreeMap::from([("classes".to_owned(), h)]))
}

