//! The walkabout set: what every map looks like from where a soldier stands.
//!
//! ```text
//! cargo run --release -p game --example walkabout [<map> ...]
//! ```
//!
//! With no arguments it does every baked map. Each map gets one 2560x1440
//! sheet per command post — four 1280x720 panels, bearings 0/90/180/270 at
//! level pitch from an eye 1.7 m over the post, with the side's rifleman
//! standing 3 m in front of the camera for scale — plus one 2560x1440
//! vantage shot. The pictures and the numbers come from
//! [`game::gallery::walkabout`]; this example only writes and tabulates them.
//!
//! Output (Tier-4, gitignored) under `engine/artifacts/walkabout/`:
//!
//! * `<map>/cp<k>_<name>.png` and `<map>/vantage.png`;
//! * `INDEX.md` — one row per image with the stand, the eye, and per panel
//!   the draw calls and how many draws the frustum culled, under a per-map
//!   line carrying that scene's untextured / dangling census.
//!
//! The INDEX is APPENDED to, so a run over two maps adds two sections to an
//! existing sheet. Delete it first for a clean full regeneration; the README
//! next to it spells that out.
//!
//! The PNGs are **RGB**: the captured alpha is a byproduct of the blend
//! passes, not a mask (36.7 % of `bf2_end1/vantage.png`'s pixels came back at
//! alpha 127..254), and a compositing viewer showed the set brighter than the
//! engine drew it — defect reports C §0 and D (3). The goldens keep theirs.
//!
//! `OPENBF_ASSETS` names a bake other than `engine/assets_baked`.
//!
//! This is the set to LOOK at. The committed goldens
//! (`engine/goldens/{maps,units}`) are the regression net that fails a test
//! when one of these pictures would have changed.

use game::gallery::{walkabout, WalkaboutSet};
use std::path::{Path, PathBuf};
use std::time::Instant;

/// Where the set is written: `engine/artifacts/walkabout`, or
/// `OPENBF_WALKABOUT_OUT` when it is set.
///
/// The override exists because `engine/artifacts` is a SYMLINK to the shared
/// tree inside every loop worktree, so a lane comparing a change against the
/// committed set would otherwise overwrite the very images it is comparing
/// against. Unset, nothing changes.
fn out_root() -> PathBuf {
    match std::env::var_os("OPENBF_WALKABOUT_OUT") {
        Some(d) => PathBuf::from(d),
        None => PathBuf::from(concat!(
            env!("CARGO_MANIFEST_DIR"),
            "/../../artifacts/walkabout"
        )),
    }
}

/// `(x, y, z)` at decimetre precision — enough to find the spot in the
/// viewer, short enough to read in a table.
fn xyz(v: glam::Vec3) -> String {
    format!("({:.1}, {:.1}, {:.1})", v.x, v.y, v.z)
}

/// The INDEX header, written once when the file does not exist yet.
const HEADER: &str = "\
# Walkabout INDEX

One row per image in this folder. Generated by
`cargo run --release -p game --example walkabout` — see `README.md`.

Each sheet is four 1280x720 panels in a 2x2 grid: **bearing 0 deg top-left,
90 deg top-right, 180 deg bottom-left, 270 deg bottom-right**. The 4-px bar
across the top of each panel is the post's starting owner through
`walk::team_color`: team 1 orange, team 2 green, anything else (0 neutral, or
a locals team) white. `vantage.png` is a single 2560x1440 panel from
`gallery::vantage_camera` and has no soldier in it.

The per-bearing cells are `draw calls / frustum-culled draws` for that panel.
";

fn write_map(out: &Path, key: &str, set: &WalkaboutSet) -> anyhow::Result<(usize, u64, f64)> {
    let dir = out.join(key);
    std::fs::create_dir_all(&dir)?;
    let mut bytes = 0u64;
    let mut rows = Vec::new();
    let mut encode_s = 0.0;
    for shot in &set.shots {
        let t = Instant::now();
        let png = render::encode_png_rgb(&shot.rgba, shot.width, shot.height)
            .map_err(|e| anyhow::anyhow!("png {}: {e}", shot.name))?;
        encode_s += t.elapsed().as_secs_f64();
        let path = dir.join(format!("{}.png", shot.name));
        std::fs::write(&path, &png)?;
        bytes += png.len() as u64;
        println!(
            "  {key}/{}.png  {}x{}  {:.1} MB  {:.2}s",
            shot.name,
            shot.width,
            shot.height,
            png.len() as f64 / 1e6,
            t.elapsed().as_secs_f64()
        );
        let mut cells: Vec<String> = shot
            .panels
            .iter()
            .map(|p| format!("{}/{}", p.draw_calls, p.culled))
            .collect();
        while cells.len() < 4 {
            cells.push("—".to_owned());
        }
        rows.push(format!(
            "| `{}.png` | {} | {} | {} | {} | {} |",
            shot.name,
            shot.post.as_deref().unwrap_or("—"),
            shot.team,
            xyz(shot.stand),
            xyz(shot.eye),
            cells.join(" | "),
        ));
    }

    let index = out.join("INDEX.md");
    let mut md = String::new();
    if !index.exists() {
        md.push_str(HEADER);
    }
    md.push_str(&format!(
        "\n## {key}\n\n\
         {} posts · {} untextured draws · {} untextured on the disc · \
         {} dangling · {} terrain chunks dropped · {} instances skipped · \
         {} sky segments V-clamped\n\n\
         | image | post | team | stand | eye | 0° | 90° | 180° | 270° |\n\
         |---|---|---:|---|---|---|---|---|---|\n",
        set.posts,
        set.untextured,
        set.disc_untextured,
        set.dangling,
        set.terrain_dropped,
        set.skipped,
        set.sky_clamped,
    ));
    md.push_str(&rows.join("\n"));
    md.push('\n');
    use std::io::Write;
    std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(&index)?
        .write_all(md.as_bytes())?;
    Ok((set.shots.len(), bytes, encode_s))
}

fn main() -> anyhow::Result<()> {
    let want: Vec<String> = std::env::args().skip(1).collect();
    // `OPENBF_ASSETS` names a bake other than `engine/assets_baked`, as `hud_capture` takes it.
    let assets =
        std::env::var_os("OPENBF_ASSETS").map_or_else(game::assets::baked_root, PathBuf::from);
    let out = out_root();
    let maps: Vec<(String, String, PathBuf)> = game::assets::discover_maps(&assets)
        .into_iter()
        .filter(|(k, _, _)| want.is_empty() || want.iter().any(|w| w == k))
        .collect();
    if maps.is_empty() {
        anyhow::bail!("no baked maps matched {want:?} under {}", assets.display());
    }
    std::fs::create_dir_all(&out)?;

    let start = Instant::now();
    let (mut images, mut bytes, mut encode_s) = (0usize, 0u64, 0.0);
    for (key, _game, dir) in &maps {
        let t = Instant::now();
        let set = walkabout(dir, &assets, 1)?;
        let render_s = t.elapsed().as_secs_f64();
        println!(
            "{key}: {} posts, {} images, rendered in {render_s:.1}s",
            set.posts,
            set.shots.len()
        );
        let (n, b, e) = write_map(&out, key, &set)?;
        images += n;
        bytes += b;
        encode_s += e;
    }
    println!(
        "\n{images} images over {} maps in {:.1}s ({:.1}s of that PNG encoding), {:.1} MB in {}",
        maps.len(),
        start.elapsed().as_secs_f64(),
        encode_s,
        bytes as f64 / 1e6,
        out.display(),
    );
    Ok(())
}
